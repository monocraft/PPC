import assert from "node:assert/strict";
await import("../../public/js/sellout-motion.js");
let time = 0, nextId = 0, cancellations = 0;
const queue = new Map();
const motion = globalThis.PPCSelloutMotion.create({ now: () => time, requestFrame: callback => { queue.set(++nextId, callback); return nextId; }, cancelFrame: id => { cancellations++; queue.delete(id); } });
function advance(next) { time = next; const callbacks = [...queue.values()]; queue.clear(); callbacks.forEach(callback => callback(time)); }
const old = [{ date: "2025-01-05", x: 0, y: 10 }, { date: "2025-01-12", x: 100, y: 20 }, { date: "2025-01-19", x: 200, y: 30 }];
const next = [{ date: "2025-01-12", x: 0, y: 40 }, { date: "2025-01-19", x: 100, y: 50 }, { date: "2025-01-26", x: 200, y: 60 }];
const domain = { start: "2025-01-05", end: "2025-01-19", left: 0, right: 200 };
const nextDomain = { ...domain, start: "2025-01-12", end: "2025-01-26" };
let frames = [];
const onFrame = frame => frames.push(structuredClone(frame));
motion.transition("weekly", old, { domain, baseline: 100, duration: 420, onFrame });
assert.deepEqual(frames[0], { samples: old, baseline: 100, settled: true });
assert.equal(queue.size, 0, "The first render must be static, with no invented starting geometry.");
motion.transition("weekly", next, { domain: nextDomain, baseline: 120, duration: 400, onFrame });
const first = frames.at(-1);
assert.equal(first.settled, false);
assert.equal(first.baseline, 100, "The area baseline must remain at displayed pixels in the immediate frame.");
assert.deepEqual(first.samples.slice(0, 3), old, "Existing displayed line/dot geometry must not flash to target pixels before interpolation.");
assert.equal(first.samples.at(-1).date, "2025-01-26");
assert.equal(first.samples.at(-1).x, 300, "Entering weeks start at an extrapolation of the old calendar projection.");
advance(200);
const middle = frames.at(-1), easeHalf = .875;
assert.equal(middle.samples.find(sample => sample.date === "2025-01-12").x, 100 + (0 - 100) * easeHalf);
assert.equal(middle.samples.find(sample => sample.date === "2025-01-12").y, 20 + (40 - 20) * easeHalf);
assert.equal(middle.samples[0].x, -100 * easeHalf, "Exiting weeks slide toward the new calendar projection outside the viewport.");
assert.equal(middle.samples.at(-1).x, 300 + (200 - 300) * easeHalf);
assert.equal(middle.baseline, 100 + 20 * easeHalf);
assert.deepEqual(motion.inspect("weekly").samples, middle.samples, "Every rendered pixel sample is cached for interruption.");

const interrupted = [{ date: "2025-01-19", x: 0, y: 70 }, { date: "2025-01-26", x: 100, y: 80 }, { date: "2025-02-02", x: 200, y: 90 }];
motion.transition("weekly", interrupted, { domain: { ...domain, start: "2025-01-19", end: "2025-02-02" }, baseline: 140, duration: 280, onFrame });
assert.ok(cancellations > 0);
const resumed = frames.at(-1);
for (const previous of middle.samples) assert.deepEqual(resumed.samples.find(sample => sample.date === previous.date), previous, "Interruptions resume current pixels, including dates already exiting.");
assert.equal(resumed.baseline, middle.baseline);
assert.equal(resumed.samples.at(-1).x, 400 - 100 * easeHalf, "A newly entering date uses the interpolated current projection, rather than a stale logical domain.");
advance(480);
assert.deepEqual(frames.at(-1), { samples: interrupted, baseline: 140, settled: true });
assert.equal(queue.size, 0, "Glides must stop requesting frames after settling.");

const gaps = [{ date: "2025-01-19", x: 0, y: null }, { date: "2025-01-26", x: 100, y: 0 }, { date: "2025-02-02", x: 200, y: 90 }];
motion.transition("weekly", gaps, { baseline: 140, domain: { ...domain, start: "2025-01-19", end: "2025-02-02" }, onFrame });
assert.equal(frames.at(-1).samples[0].y, null, "Missing observations become line/fill gaps, never a zero baseline.");
advance(690); assert.equal(frames.at(-1).samples[0].y, null);
advance(900); assert.equal(frames.at(-1).samples[1].y, 0, "A real zero coordinate remains distinct from null.");
const newObserved = [{ ...gaps[0], y: 55 }, gaps[1], gaps[2]];
motion.transition("weekly", newObserved, { baseline: 140, onFrame });
assert.equal(frames.at(-1).samples[0].y, 55, "Previously missing observations appear at their actual y, without inventing a numeric baseline.");
motion.cancel("weekly"); assert.equal(queue.size, 0); assert.equal(motion.inspect("weekly").running, false);

motion.transition("weekly", next, { baseline: 0, domain: nextDomain, reducedMotion: true, onFrame });
assert.deepEqual(frames.at(-1), { samples: next, baseline: 0, settled: true });
assert.equal(queue.size, 0);
motion.transition("weekly", next, { baseline: 0, domain: nextDomain, onFrame });
assert.equal(frames.at(-1).settled, true, "Unchanged geometry does not animate.");
motion.transition("weekly", [], { baseline: 0, onFrame });
assert.deepEqual(frames.at(-1), { samples: [], baseline: 0, settled: true });
motion.reset("weekly"); assert.equal(motion.inspect("weekly"), null);

const one = [{ date: "2025-01-05", x: 100, y: 10 }], two = [{ date: "2025-01-12", x: 100, y: 20 }];
motion.transition("one", one, { baseline: 50, domain: { ...domain, end: domain.start }, onFrame });
motion.transition("one", two, { baseline: 50, domain: { ...domain, start: "2025-01-12", end: "2025-01-12" }, onFrame });
assert.equal(frames.at(-1).samples.at(-1).x, 300, "A one-week view has a finite weekly extrapolation for entering weeks.");
motion.reset(); assert.equal(queue.size, 0); assert.equal(motion.inspect("one"), null);

const before = structuredClone(old);
motion.transition("immutable", old, { baseline: 100, domain, onFrame: frame => { frame.samples[0].x = 999; } });
assert.deepEqual(old, before); assert.deepEqual(motion.inspect("immutable").samples, old, "Callback mutation cannot alter input or cached pixels.");
assert.throws(() => motion.transition("bad", [{ date: "2025-02-30", x: 0, y: 1 }], { onFrame }), /ISO dates/);
assert.throws(() => motion.transition("bad", [old[0], old[0]], { onFrame }), /unique ascending/);
assert.throws(() => motion.transition("bad", [{ date: "2025-01-05", x: NaN, y: 1 }], { onFrame }), /finite x/);
assert.throws(() => motion.transition("bad", [{ date: "2025-01-05", x: 0, y: undefined }], { onFrame }), /finite or null y/);
assert.throws(() => motion.transition("bad", old, { domain: { ...domain, end: "2024-01-01" }, onFrame }), /ordered ISO/);
assert.throws(() => motion.transition("bad", old, { baseline: null, onFrame }), /baseline/);
assert.throws(() => motion.transition("error", old, { onFrame: () => { throw new Error("frame failed"); } }), /frame failed/);
assert.equal(queue.size, 0, "Callback failures cannot leave animation requests running.");
motion.reset();
console.log("Time-window motion: calendar extrapolation, shared x/y/baseline tween, displayed-pixel interruption, gaps/zero, singleton weeks, reduced motion, cancellation/reset, mutation isolation, and finite cleanup passed.");
